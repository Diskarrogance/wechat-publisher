def find_hits(text, words):
    """返回 text 中命中的词列表（去重、保持原顺序）"""
    if not text:
        return []
    seen, out = set(), []
    for w in words:
        if w in text and w not in seen:
            seen.add(w)
            out.append(w)
    return out


def find_hits_with_context(text, words, window=18, limit=8):
    """返回 [(词, 上下文片段)]，用于把命中位置摊开给人看

    window: 命中词前后各截取多少字
    limit : 最多返回多少条（防刷屏）
    """
    out = []
    if not text:
        return out
    for w in words:
        start = 0
        while len(out) < limit:
            i = text.find(w, start)
            if i < 0:
                break
            a = max(0, i - window)
            b = min(len(text), i + len(w) + window)
            ctx = text[a:b].replace('\n', ' ')
            out.append((w, ('…' if a > 0 else '') + ctx + ('…' if b < len(text) else '')))
            start = i + len(w)
        if len(out) >= limit:
            break
    return out
